const resources: PermissionResource[] = ['Filesystem', 'Git', 'Terminal', 'Browser', 'Microsoft 365', 'Gmail', 'Calendar', 'Production', 'Deployment', 'Client data', 'Financial data']
const defaultLevel = (agentId: string, resource: PermissionResource): PermissionLevel => {
  if (resource === 'Gmail') return 'None'
  if (resource === 'Production') return agentId === 'deployment' ? 'Approval Required' : 'None'
  if (resource === 'Deployment') return agentId === 'deployment' ? 'Execute' : agentId === 'master-pm' ? 'Approval Required' : 'None'
  if (resource === 'Microsoft 365') return agentId === 'deployment' ? 'Approval Required' : 'None'
  if (resource === 'Calendar') return agentId === 'master-pm' ? 'Read' : 'None'
  if (resource === 'Client data') return ['revenue', 'client-portal', 'executive'].includes(agentId) ? 'Read' : 'None'
  if (resource === 'Financial data') return ['finance', 'executive', 'master-pm'].includes(agentId) ? 'Approval Required' : 'None'
  if (resource === 'Browser') return ['revenue', 'client-portal', 'executive', 'finance', 'operations', 'qa-release'].includes(agentId) ? 'Execute' : 'None'
  if (resource === 'Terminal') return ['documentation'].includes(agentId) ? 'Read' : 'Execute'
  return agentId === 'qa-release' ? 'Read' : 'Write'
}

