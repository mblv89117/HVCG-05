const execRoles: Role[] = ['Owner', 'Executive', 'Finance', 'Advisor']
const financeRoles: Role[] = ['Owner', 'Executive', 'Finance']

function usd(n: number): string {
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(n)
}

function incompleteKpi(
  id: string,
  label: string,
  organizationId: OrganizationId,
  drillDownPath: string,
  quality: FinanceKpi['dataQuality'] = 'Awaiting verified data',
): FinanceKpi {
  return {
    id,
    label,
    currentValue: null,
    displayValue: quality,
    unit: 'text',
    reportingPeriod: 'Not bound',
    priorPeriodValue: null,
    priorPeriodComparison: 'Not yet calculated',
    trend: 'unknown',
    trendLabel: 'No trend — incomplete data',
    source: 'Approved Atlas sources (relationship only for CCB)',
    sourceIds: ['src-ccb-finance-gate', 'src-ccb-relationship'],
    lastRefresh: GENERATED_AT,
    status: 'Incomplete',
    drillDownPath,
    dataQuality: quality,
    organizationId,
    allowedRoles: execRoles,
  }
}

